module Command

  ##################################################################################################
  # help
  ##################################################################################################
  define :help do
    usage
    usage :command
    exec do
      if command
        user.puts "Executed HELP for command '#{command}'"
      else
        user.puts "Executed HELP"
      end
    end
  end

  ##################################################################################################
  # quit
  ##################################################################################################
  define :quit do
    usage
    exec do
      user.puts "Logging out. Goodbye."
      user.client.should_terminate = true
    end
  end

  ##################################################################################################
  # say
  ##################################################################################################
  define :say do
    usage :rest
    exec do
      user.puts "You say, \"#{rest}\""
    end
  end

  ##################################################################################################
  # look
  ##################################################################################################
  define :look do
    usage
    exec do
      user.puts "You look around."
    end
  end

end
