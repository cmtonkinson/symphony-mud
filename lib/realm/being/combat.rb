module Realm

  class Being
    attr_reader :group
    attr_accessor :pending_group

    define_hooks :before_strike_attack, :after_strike_attack
    define_hooks :before_strike_defense, :after_strike_defense
    define_hook :before_death, halts_on_falsey: true
    define_hook :on_death
    define_hook :after_death

    ###########################################################################
    after_initialize -> {
      @dead  = false
      Combat::Group.new self
      @pending_group = nil
    }

    ###########################################################################
    def set_group(group)
      @group = group
    end

    ###########################################################################
    def battle
      group.battle
    end

    ###########################################################################
    def acquire_target
      group.all_opponent_members
        .reject { |b| b.dead? }
        .reject { |b| b.room != room }
        .first
    end

    ###########################################################################
    def dead?
      @dead
    end

    ###########################################################################
    def emit_experience
      # Short circuit if the Being didn't die in combat.
      return unless group.battle

      # Calculate experience generated by this death.
      experience_given = level * 10

      # Grant experience to each Group in the Battle that sees this Being as
      # an opponent.
      cui_bono = group.battle.groups.select { |g| g.opponents.include? group }
      cui_bono.each { |g| g.award_experience experience_given, self }
    end

    ###########################################################################
    before_strike_attack -> (strike) {
    }

    ###########################################################################
    after_strike_attack -> (strike) {
      # TODO: Leaving this here as a reminder of how to implement e.g. Second Strike
      #return if strike.parent
      #Combat::Strike.new strike.attacker, strike.defender, strike.bout, strike
    }

    ###########################################################################
    before_strike_defense -> (strike) {
    }

    ###########################################################################
    after_strike_defense -> (strike) {
    }

    ###########################################################################
    before_death -> {
      return false if god?
      return true
    }

    ###########################################################################
    on_death -> {
      @dead = true
      emit_experience
    }
  end

end

