module Realm
  class Being
    attr_accessor :group, :pending_group

    define_hook :before_strike_attack, halts_on_falsey: true
    define_hook :after_strike_attack
    define_hook :before_strike_defense
    define_hook :after_strike_defense
    define_hook :before_death, halts_on_falsey: true
    define_hook :on_death
    define_hook :after_death

    ###########################################################################
    after_initialize -> {
      @dead = false
      Combat::Group.new self
      @pending_group = nil
    }

    ###########################################################################
    def battle
      group.battle
    end

    ###########################################################################
    def acquire_target
      return nil unless group.all_opponent_members

      group.all_opponent_members
           .reject { |b| b.dead? }
           .reject { |b| b.room != room }
           .first
    end

    ###########################################################################
    def dead?
      @dead
    end

    ###########################################################################
    def emit_experience
      # Short circuit if the Being didn't die in combat.
      return unless group.battle

      # Calculate experience generated by this death; a random value which is
      # within 20% of the level x 10.
      adjustment = Random.rand(80..120)
      experience_given = level * adjustment / 10

      # Grant experience to each Group in the Battle that sees this Being as
      # an opponent.
      cui_bono = group.battle.groups.select { |g| g.opponents.include? group }
      cui_bono.each { |g| g.award_experience experience_given, self }
    end

    ###########################################################################
    def cast_spell(ability, target)
      puts "You intone the '{c$ability{x' spell.", ability
      room.puts '$being mutters something strange.', self, exclude: [self]
      ability.invoke target
    end

    ###########################################################################
    before_strike_attack ->(strike) {}

    ###########################################################################
    after_strike_attack ->(strike) {
      # TODO: Leaving this here as a reminder of how to implement e.g. Second Strike
      # return if strike.parent
      # Combat::Strike.new strike.attacker, strike.defender, strike.bout, strike
    }

    ###########################################################################
    before_strike_defense ->(strike) {}

    ###########################################################################
    after_strike_defense ->(strike) {}

    ###########################################################################
    before_death -> {
      if god?
        health.increase 1
        return false
      end

      return true
    }

    ###########################################################################
    on_death -> {
      @dead = true
      emit_experience
    }
  end
end
